import assert from 'node:assert/strict'
import { PROGRESS_TOTAL, connectionProblem, initialState, installationProblem, lab, missingPower, mountProblem, placementProblem, portAvailable, progress } from '../src/state.ts'
import { GRAPHICS_IDS, MOUNT, PARTS, PART_IDS, PLATFORM_IDS, PORTS, SOLDER, WIRES, WIRE_IDS } from '../src/config.ts'
import type { LabState, Phase } from '../src/state.ts'

const s = initialState()
const full: LabState = { ...s, installed: [...PART_IDS], soldered: true, wires: [...WIRE_IDS], card: 'mounted' }
const onBench: LabState = { ...s, installed: [...PART_IDS], soldered: true, wires: ['fan'], card: 'bench' }

// The platform chain: shield, board, then everything that bolts to the board, then the cooler.
assert.equal(installationProblem(s, 'shield'), null, 'the IO shield is the first thing into the case')
assert(installationProblem(s, 'board')?.includes(PARTS.shield.name), 'the board cannot drop in past an empty IO opening')
for (const id of ['cpu', 'dimmA', 'dimmB'] as const) assert(installationProblem(s, id)?.includes(PARTS.board.name), id)
assert(installationProblem(s, 'cooler')?.includes(PARTS.cpu.name) && installationProblem(s, 'cooler')?.includes(PARTS.dimmA.name))
assert(installationProblem(s, 'psu') === null, 'the power supply sits in its own bay')
for (const id of PART_IDS) assert(installationProblem({ ...s, power: 'booting' }, id)?.includes('通电'), id)
for (const id of PLATFORM_IDS) assert.equal(installationProblem({ ...s, phase: 'assembly' as Phase, installed: PART_IDS.filter(p => p !== id) }, id), null, id)

// Placement: slot distance plus the ninety degrees every rotated part ships in.
assert(placementProblem(s, 'shield', [8, 8, 8]), 'a far position must be rejected')
assert.equal(placementProblem(s, 'shield', PARTS.shield.slot), null)
for (const id of PART_IDS) {
  if (!PARTS[id].initialAngle) continue
  const ready: LabState = { ...s, installed: PARTS[id].dependencies }
  assert(placementProblem(ready, id, PARTS[id].slot)?.includes('方向'), `${id} ships rotated`)
  assert.equal(placementProblem({ ...ready, angles: { ...s.angles, [id]: 0 } }, id, PARTS[id].slot), null, id)
}

// The card chain, ending with the reflow interlock that gates the fin stack.
assert(installationProblem(s, 'core')?.includes(PARTS.pcb.name), 'the die needs the carrier board first')
assert(installationProblem({ ...s, installed: ['pcb', 'core'] }, 'heatsink')?.includes('回流焊'), 'the fin stack waits for a solidified joint')
assert.equal(installationProblem({ ...s, installed: ['pcb', 'core'], soldered: true }, 'heatsink'), null)
assert(installationProblem({ ...s, installed: ['pcb', 'core'], soldered: true }, 'fan')?.includes(PARTS.heatsink.name), 'the fan bolts to the fin stack')
assert(installationProblem({ ...s, card: 'mounted' }, 'pcb'), 'a card in the slot is not a workbench')

// Port ownership plus where a port is allowed to be touched.
for (const id of WIRE_IDS.flatMap(w => WIRES[w].ends).filter(p => PORTS[p].owner !== 'external')) assert(!portAvailable(s, id), `${id} needs its owner`)
assert(portAvailable(s, 'D2') && portAvailable(s, 'M2'), 'the monitor and the wall socket are always there')
assert(portAvailable({ ...s, installed: ['pcb', 'fan'] }, 'F1') && portAvailable({ ...s, installed: ['pcb', 'fan'] }, 'F2'))
assert(portAvailable(onBench, 'F1'), 'the fan header lives on the bench')
assert(!portAvailable({ ...full }, 'F1'), 'the fan header disappears once the card is in the slot')
assert(!portAvailable({ ...s, installed: ['pcb'] }, 'G2') && !portAvailable({ ...s, installed: ['pcb'] }, 'D1'), 'card power and display need the slot')
assert(portAvailable(full, 'G2') && portAvailable(full, 'D2'), 'the case-side sockets open after mounting')
assert.equal(connectionProblem({ ...s, installed: ['pcb', 'fan'] }, 'F1', 'F2'), null)
assert(connectionProblem(s, 'F1', 'F2')?.includes('尚不可用'))
assert(connectionProblem(s, 'F1', 'F1')?.includes('自身'))
assert(connectionProblem({ ...s, installed: ['pcb', 'fan', 'psu', 'board'] }, 'A1', 'F1')?.includes('不兼容'))
assert(connectionProblem({ ...s, installed: ['pcb', 'fan'], power: 'on' }, 'F1', 'F2')?.includes('关机'))
assert(connectionProblem(full, 'A1', 'A2')?.includes('已经连接'), 'a live cable blocks a second one')

// Mounting gates: the four card parts, the joint, the internal fan cable, and the board itself.
assert(mountProblem(s)?.includes('显卡组件'), 'an empty card cannot enter the slot')
assert(mountProblem({ ...s, installed: [...GRAPHICS_IDS] })?.includes('回流焊'))
assert(mountProblem({ ...s, installed: [...GRAPHICS_IDS], soldered: true })?.includes('风扇线'))
assert(mountProblem({ ...s, installed: [...GRAPHICS_IDS], soldered: true, wires: ['fan'], card: 'bench' }))
assert.equal(mountProblem(onBench), null)
assert(mountProblem({ ...onBench, installed: onBench.installed.filter(p => p !== 'board') })?.includes('主板'))
assert(mountProblem({ ...full })?.includes('已经插'))

// What the power button still wants, and the complete preflight.
assert.equal(missingPower(s)[0].target, PART_IDS[0])
assert.equal(missingPower(s).length, PROGRESS_TOTAL, 'the preflight lists every step of a twenty-part build')
assert.equal(missingPower(full).length, 0)
assert.equal(progress(full), PROGRESS_TOTAL)
for (const id of PART_IDS) assert(missingPower({ ...full, installed: full.installed.filter(p => p !== id) }).some(x => x.target === id), id)
for (const id of WIRE_IDS) assert(missingPower({ ...full, wires: [] }).some(x => WIRES[id].ends.includes(x.target as never)), id)
assert(missingPower({ ...full, soldered: false }).some(x => x.target === 'core'))
assert(missingPower({ ...full, card: 'bench' }).some(x => x.target === 'pcb'))
assert.equal(missingPower({ ...full, wires: ['fan'] }).length, WIRE_IDS.length - 1)

// The live store: seating, rotation, scorch versus dwell, mounting and powered locks.
lab.start()
const seat = (id: (typeof PART_IDS)[number]) => {
  lab.select(id)
  if (PARTS[id].initialAngle) lab.rotate()
  assert(lab.attempt(id, PARTS[id].slot), id)
  lab.seated(id, lab.get().epoch)
}
assert.equal(lab.attempt('shield', PARTS.shield.slot), false, 'nothing seats before the platform opens')
lab.select('pcb')
assert.equal(lab.get().selected, null, 'the dock refuses to select outside assembly')
lab.arranged()
for (const id of ['shield', 'board'] as const) seat(id)
assert.equal(lab.get().seating, null)
lab.select('cpu')
assert(lab.attempt('cpu', PARTS.cpu.slot) === false, 'the processor must be turned the right way first')
lab.rotate()
assert.equal(lab.get().angles.cpu, 0, 'one quarter turn lands the processor')
assert(lab.attempt('cpu', PARTS.cpu.slot))
assert.equal(lab.get().seating, 'cpu')
lab.seated('cpu', lab.get().epoch)
lab.seated('cpu', lab.get().epoch - 1)
assert.equal(lab.get().installed.length, 3, 'a stale seating callback must not double-install')
for (const id of ['dimmA', 'dimmB', 'psu', 'cooler'] as const) seat(id)
assert.equal(lab.get().installed.length, 7)
seat('pcb'); seat('core')
assert(!lab.get().soldered)
lab.heat(true)
for (let i = 0; i < 400 && lab.get().scorches === 0; i++) lab.tick(.05)
const scorched = lab.get()
assert(scorched.scorches === 1 && !scorched.heating && !scorched.soldered && scorched.temp > SOLDER.ceiling, 'holding past the ceiling scorches instead of soldering')
assert(scorched.reflow < 100, 'the window is longer than the dwell, so a full press must overshoot')
for (let i = 0; i < 400 && !lab.get().soldered && lab.get().temp > 80; i++) lab.tick(.05)
assert(lab.get().reflow >= scorched.reflow, 'descending back through the window keeps the joint forming')
for (let i = 0; i < 400 && !lab.get().soldered; i++) { lab.heat(lab.get().temp < 262); lab.tick(.05) }
const reflow = lab.get()
assert(reflow.soldered && reflow.reflow === 100 && !reflow.heating, 'pumping inside 200-275C completes the joint')
assert(reflow.temp >= SOLDER.target && reflow.temp <= SOLDER.ceiling)
lab.heat(true)
assert.equal(lab.get().heating, false, 'a finished joint cannot be reheated')
for (const id of ['heatsink', 'fan'] as const) seat(id)
assert.equal(lab.get().installed.length, 11)
assert(lab.connect('F1', 'F2') && lab.get().wires.includes('fan'))
assert.equal(lab.attemptMount([0, 0, 0]), false, 'the fingers must reach the slot')
assert(lab.attemptMount(MOUNT.position))
lab.mounted(lab.get().epoch)
assert.equal(lab.get().card, 'mounted')
assert(lab.disconnect('fan') === undefined && lab.get().wires.includes('fan'), 'internal wiring needs the card back on the bench')
for (const id of ['pcie', 'atx', 'eps', 'cpufan', 'dp', 'mains'] as const) assert(lab.connect(...WIRES[id].ends), id)
assert.equal(lab.get().wires.length, WIRE_IDS.length)
assert.equal(missingPower(lab.get()).length, 0)
assert.equal(progress(lab.get()), PROGRESS_TOTAL)
lab.power()
assert.equal(lab.get().power, 'booting')
assert(installationProblem(lab.get(), 'board')?.includes('通电'))
assert(connectionProblem(lab.get(), 'A1', 'A2')?.includes('通电'))
lab.remove('board')
assert(lab.get().installed.includes('board'), 'parts are locked while powered')
lab.power()
assert.equal(lab.get().power, 'off')
lab.remove('board')
assert(lab.get().installed.includes('board') && lab.get().card === 'mounted', 'a card in the slot blocks the motherboard tray')
lab.disconnect('pcie'); lab.disconnect('dp')
lab.unmount()
assert.equal(lab.get().card, 'bench', 'the card lifts out once the slot is free')
lab.remove('board')
assert(lab.get().installed.includes('board'), 'the processor and the memory still sit on that board')
assert.equal(lab.get().soldered, true, 'a detached card keeps its joint')
lab.remove('fan')
assert(lab.get().installed.includes('fan'), 'the fan cable holds the fan in place')
lab.disconnect('fan')
lab.remove('fan')
assert(!lab.get().installed.includes('fan'))
lab.select('heatsink')
assert.equal(lab.get().selected, 'heatsink')
lab.rotate()
assert.equal(lab.get().angles.heatsink, 0, 'an installed part is rotation-locked')
lab.select('heatsink')
assert.equal(lab.get().selected, null, 'selecting the same part clears the choice')
lab.remove('core')
assert(lab.get().installed.includes('core'), 'a dependent part must come off first')
lab.remove('heatsink')
lab.remove('core')
assert(!lab.get().soldered && lab.get().reflow === 0, 'pulling the die kills the joint')
assert(lab.get().installed.length === PART_IDS.length - 3 && !lab.get().soldered)
const epoch = lab.get().epoch
lab.reset()
assert(lab.get().epoch > epoch && progress(lab.get()) === 0 && lab.get().power === 'off' && !lab.get().soldered && lab.get().scorches === 0)
console.log('Rules passed: platform chain, rotated parts, scorch versus dwell, port gating, mount preflight, seven cables, powered locks, removal interlocks, epoch-safe reset.')
