import { chromium } from 'playwright-core'
import assert from 'node:assert/strict'
import os from 'node:os'
import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'
const out = process.env.TEST_OUTPUT || join(os.tmpdir(), 'volta-qa')
const url = process.env.TEST_URL || 'http://127.0.0.1:4408/'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--disable-dev-shm-usage'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const read = () => page.evaluate(() => window.__VOLTA__.read())
const errors = []; page.on('pageerror', e => errors.push(e.message))
await page.goto(url)
await page.getByText('开始组装', { exact: true }).click()
await page.waitForFunction(() => window.__VOLTA__?.read().state.phase !== 'intro')
await page.waitForTimeout(2600)
let d = await read()
const p = d.parts.pcb.screen
await page.mouse.move(p.x + 30, p.y + 6); await page.mouse.down(); await page.mouse.move(700, 700, { steps: 14 }); await page.mouse.up()
await page.waitForTimeout(600)
d = await read(); assert(!d.state.installed.includes('pcb'), 'a bad drop must not install')
assert.equal(d.state.notice.kind, 'error', 'a wrong drop must produce feedback')
await page.waitForTimeout(700)
d = await read()
const from = d.parts.pcb.screen, to = d.parts.pcb.slot
await page.mouse.move(from.x + 30, from.y + 6); await page.mouse.down()
assert.equal((await read()).camera.enabled, false, 'component drag must lock the camera')
await page.mouse.move(to.x + 30, to.y + 6, { steps: 20 }); await page.mouse.up()
await page.waitForFunction(() => window.__VOLTA__.read().state.installed.includes('pcb'))
await page.getByTestId('part-core').click()
await page.locator('[data-slot="core"]').click()
assert.match((await read()).state.notice.detail, /方向/, 'a rotated die must be refused')
await page.getByTestId('wires-mode').click()
await page.locator('[data-port="F1"]').click()
await page.locator('[data-port="P1"]').click()
assert.equal((await read()).state.wires.length, 0)
assert.match((await read()).state.notice.detail, /不兼容/)
let a = await page.locator('[data-port="F1"]').boundingBox(), b = await page.locator('[data-port="F2"]').boundingBox()
await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2); await page.mouse.down(); await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 12 }); await page.mouse.up()
assert.equal((await read()).state.wires.length, 0, 'a port needs its owner installed first')
assert.match((await read()).state.notice.detail, /尚不可用/)
await page.getByTestId('power').click(); assert.equal((await read()).state.power, 'off', 'an incomplete card cannot boot')
await page.screenshot({ path: `${out}/prototype-desktop.png` })
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
await mobile.goto(url)
await mobile.getByText('开始组装', { exact: true }).tap()
await mobile.waitForFunction(() => window.__VOLTA__.read().state.phase !== 'intro')
await mobile.waitForTimeout(2600)
await mobile.getByTestId('part-pcb').tap()
await mobile.locator('[data-slot="pcb"]').tap()
await mobile.waitForFunction(() => window.__VOLTA__.read().state.installed.includes('pcb'))
await mobile.screenshot({ path: `${out}/prototype-mobile.png` })
assert.equal(errors.length, 0, errors.join('\n'))
console.log('Prototype passed: wrong drop rejected; PCB slot snap with camera lock; rotated die refused; incompatible ports refused; mobile PCB tap-install; incomplete boot blocked; no page errors.')
await browser.close()
